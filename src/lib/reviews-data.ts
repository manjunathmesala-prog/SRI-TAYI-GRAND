// Helper functions & aliases for backwards-compatibility across subagents
export const INITIAL_REVIEWS_DATA: GoogleReview[] = INITIAL_GOOGLE_REVIEWS;
export const REVIEWS_DATA: GoogleReview[] = INITIAL_GOOGLE_REVIEWS;
export const featuredReviews: GoogleReview[] = INITIAL_GOOGLE_REVIEWS.filter(
  (r) => r.is_featured && r.is_published
);

export function getAllReviews(includeUnpublished = false): GoogleReview[] {
  return includeUnpublished
    ? INITIAL_GOOGLE_REVIEWS
    : INITIAL_GOOGLE_REVIEWS.filter((r) => r.is_published);
}

export function getFeaturedReviews(limit = 6): GoogleReview[] {
  return INITIAL_GOOGLE_REVIEWS.filter((r) => r.is_published && r.is_featured).slice(0, limit);
}
